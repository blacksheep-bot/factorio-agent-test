#!/usr/bin/env python3
"""Write FLE's generated agent system prompt (type defs + entity classes + every tool's
signature and agent.md manual) to docs/research/fle-system-prompt.md.
Does NOT connect to Factorio (constructing a FactorioInstance would reset the world)."""
import os
from pathlib import Path
import importlib.util

ROOT = Path(__file__).resolve().parent.parent
env_dir = Path(importlib.util.find_spec("fle").submodule_search_locations[0]) / "env"
from fle.env.utils.controller_loader.system_prompt_generator import SystemPromptGenerator  # noqa: E402

text = SystemPromptGenerator(str(env_dir)).generate_for_agent(agent_idx=0, num_agents=1)
out = ROOT / "docs" / "research" / "fle-system-prompt.md"
out.write_text("<!-- generated by setup/dump_system_prompt.py from factorio-learning-environment 0.4.3 -->\n" + text)
print(f"wrote {out} ({len(text)} chars)")
